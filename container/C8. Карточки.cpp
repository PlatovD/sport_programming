void solve() {
    int n, num;
    cin >> n;
    int cnt = 0;

    int last = 0;
    map<int, int> counts;
    for (int i = 0; i < n; i++) {
        int nums = i + 1;
        cin >> num;
        counts[num]++;
        if (counts[num] > counts[last]) {
            last = num;
        }
        if (counts[last] > nums - counts[last]) {
            cnt++;
        }
    }
    cout << cnt;
}

