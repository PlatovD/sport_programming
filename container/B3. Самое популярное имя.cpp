void solve() {
    int n;
    cin >> n;

    map<string, int> counts;
    string s;
    while (n--) {
        cin >> s;
        counts[s]++;
    }

    int max_cnt = -1;
    for (auto kv: counts) {
        max_cnt = max(max_cnt, kv.second);
    }

    for (auto kv: counts) {
        if (kv.second != max_cnt) continue;
        cout << kv.first << ' ';
    }
}

