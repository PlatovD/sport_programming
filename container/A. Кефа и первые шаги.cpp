void solve() {
    int n;
    cin >> n;

    vector<int> a(n);
    for (int i = 0; i < n; i++) cin >> a[i];

    int ans = 1;
    int cur_len = 1;
    int last_num = INT32_MAX;
    for (int i = 0; i < n; i++) {
        if (last_num > a[i]) {
            ans = max(ans, cur_len);
            cur_len = 0;
        }
        cur_len++;
        last_num = a[i];
    }
    ans = max(ans, cur_len);

    cout << ans;
}

