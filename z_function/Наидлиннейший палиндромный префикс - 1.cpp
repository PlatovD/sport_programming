bool check_palindrome(string &s) {
    int l = 0, r = s.size() - 1;
    while (l < r) {
        if (s[l] != s[r]) return false;
        l++;
        r--;
    }
    return true;
}

void solve() {
    string s;

    cin >> s;
    string current_prefix;
    current_prefix.reserve(2000);

    int max_len = 0;
    for (int i = 0; i < s.size(); i++) {
        current_prefix += s[i];
        if (check_palindrome(current_prefix)) {
            max_len = i + 1;
        }
    }

    cout << max_len << '\n';
}

