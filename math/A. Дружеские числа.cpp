ll MOD = 1e9 + 7;

ll sum_digits(ll n) {
    ll res = 0;
    while (n > 0) {
        res += n % 10;
        n /= 10;
    }
    return res;
}

void solve() {
    ll x;
    cin >> x;

    int cnt = 0;
    for (ll y = x; y < x + 101; y++) {
        if (y - sum_digits(y) == x) cnt++;
    }
    cout << cnt << '\n';
}

